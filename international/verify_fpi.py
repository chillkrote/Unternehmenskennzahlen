"""Gleicht die importierten Werte der SEC-Melder mit 20-F/40-F (Pilot sec_fpi_pilot.csv) mit den Finanzberichtsseiten (R2.htm ...) des Filings ab.

Je Unternehmen und Kennzahl wird die jüngste Periode des jüngsten Jahresberichts (20-F, 40-F oder 10-K) mit der Zeile im Filing verglichen.
Ergebnis: pruefung_sec_fpi.csv (status gleich / gleich_andere_zeile / abweichung / nicht_gefunden). Nur 'gleich' und 'gleich_andere_zeile' (Wert und Stichwort stimmen) zählen als bestätigt.
Aufruf: INTERNATIONAL_USER_AGENT=... INTERNATIONAL_DATABASE_URL=... python3 international/verify_fpi.py
"""
import csv
import html
import re
import sys
from collections import Counter
from datetime import date
from decimal import Decimal
from pathlib import Path

HIER = Path(__file__).resolve().parent
sys.path.insert(0, str(HIER))
import db  # noqa: E402
from httpsafe import SichererClient, atomar_speichern  # noqa: E402

LABELS = {
    "assets": [r"total assets"],
    "equity": [r"total equity attributable to .*", r"equity attributable to .*", r"total (?:stockholders|shareholders|shareowners)[’'`]*s?[’'`]* equity", r"total shareholders[’'`]* equity attributable.*", r"total equity"],
    "equity_incl_nci": [r"total equity", r"total (?:stockholders|shareholders|shareowners)[’'`]*s?[’'`]* equity"],
    "revenue": [r"total (?:net )?revenues?", r"revenues?", r"net sales", r"total net sales", r"sales", r"revenue from contracts with customers", r"operating revenues?", r"total operating revenues?"],
    "net_income": [r"net income(?: \(loss\))? attributable to .*", r"profit(?: \(loss\))? for the (?:year|period) attributable to .*", r"profit attributable to .*", r"net profit attributable to .*",
                   r"net income(?: \(loss\))?", r"net earnings(?: attributable to .*)?", r"net loss"],
    "net_income_incl_nci": [r"profit(?: \(loss\))? for the (?:year|period)", r"net income(?: \(loss\))?", r"net profit(?: for the year)?", r"profit(?: \(loss\))?", r"net earnings"],
    "operating_cash_flow": [r"net cash (?:provided by|from|provided by \(used in\)|from \(used in\)|generated by|flows? from) operating activities.*", r"net cash provided by operations",
                            r"cash generated from operating activities", r"cash flows? from(?: \(used in\))? operating activities", r"net cash from operating activities"],
}
SEITEN = range(2, 13)
SCHLUESSEL = {"assets": ["assets"], "equity": ["equity"], "equity_incl_nci": ["equity"], "revenue": ["revenue", "sales"],
              "net_income": ["net income", "net earnings", "net loss", "profit"], "net_income_incl_nci": ["net income", "net earnings", "net loss", "profit"],
              "operating_cash_flow": ["operating activities", "operations"]}
FORMULARE = ("20-F", "20-F/A", "40-F", "40-F/A", "10-K", "10-K/A")


def zahl(text):
    t = html.unescape(text).replace(",", "").replace("\xa0", " ").strip()
    t = re.sub(r"^[^\d(\-]*(?=[\d(\-])", "", t)           # Währungszeichen oder -kürzel vor der Zahl
    t = re.sub(r"\s*(?:\[\d+\]|\*+)$", "", t)              # Fußnotenmarken
    m = re.fullmatch(r"\(?\s*(-?[\d.]+)\s*\)?", t)
    if not m:
        return None
    try:
        v = Decimal(m.group(1))
    except ArithmeticError:
        return None
    return -v if t.startswith("(") else v


def seite_lesen(text):
    kopf = text[:6000]
    skal = Decimal(10) ** (9 if re.search(r"In Billions|Billions of", kopf, re.I) else 6 if re.search(r"In Millions|Millions of", kopf, re.I)
                           else 3 if re.search(r"In Thousands|Thousands of", kopf, re.I) else 0)
    zeilen = []
    for row in re.split(r"</tr>", text):
        zellen = [re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", c))).strip() for c in re.findall(r"<t[dh][^>]*>(.*?)</t[dh]>", row, re.S)]
        werte = [w for w in (zahl(z) for z in zellen[1:]) if w is not None]
        if zellen and werte:
            zeilen.append((zellen[0], werte))
    return skal, zeilen


def main():
    ciks = {r["cik"].lstrip("0") for r in csv.DictReader(open(HIER / "sec_fpi_pilot.csv", encoding="utf-8"))}
    client = SichererClient({"www.sec.gov"}, max_bytes=5_000_000)
    ausgabe = []
    with db.verbinden() as conn:
        entitaeten = conn.execute("SELECT e.id, e.legal_name, i.value FROM international.entity e JOIN international.identifier i ON i.entity_id=e.id AND i.scheme='CIK' ORDER BY e.id").fetchall()
        for uid, name, cik in entitaeten:
            if cik.lstrip("0") not in ciks:
                continue
            r = conn.execute("SELECT provenance->>'accn', max(reported_at) FROM international.fact WHERE entity_id=%s AND provenance->>'form' = ANY(%s) "
                             "GROUP BY 1 ORDER BY 2 DESC LIMIT 1", (uid, list(FORMULARE))).fetchone()
            if not r:
                continue
            accn = r[0]
            seiten = {}
            for n in SEITEN:
                url = f"https://www.sec.gov/Archives/edgar/data/{int(cik)}/{accn.replace('-', '')}/R{n}.htm"
                pfad = HIER / "objektspeicher" / "sec" / "filings" / f"{accn}_R{n}.htm"
                if not pfad.exists():
                    try:
                        atomar_speichern(pfad.parent, pfad.name, client.holen(url))
                    except Exception:
                        continue
                seiten[n] = seite_lesen(pfad.read_text(encoding="utf-8", errors="ignore"))
            for metric in LABELS:
                zeile = conn.execute(
                    "SELECT value, period_end, period_start, provenance->>'tag', unit FROM international.fact WHERE entity_id=%s AND metric_code=%s AND provenance->>'accn'=%s "
                    "ORDER BY period_end DESC, unit LIMIT 1", (uid, metric, accn)).fetchone()
                if not zeile:
                    continue
                wert, ende, beginn, tag, einheit = zeile
                gefunden = None
                for muster in LABELS[metric]:
                    for n, (skal, zl) in seiten.items():
                        for label, werte in zl:
                            if re.fullmatch(muster, label.strip().lower().rstrip(":")):
                                treffer = next((w * skal for w in werte if w * skal == wert), None)   # jede Spalte (z. B. Komfortübersetzung in USD zuerst)
                                gefunden = (n, label, treffer if treffer is not None else werte[0] * skal)
                                break
                        if gefunden:
                            break
                    if gefunden:
                        break
                if gefunden and gefunden[2] == wert:
                    status = "gleich"
                else:
                    andere = next(((n2, lb, w2 * skal) for n2, (skal, zl) in seiten.items() for lb, w in zl for w2 in w
                                   if w2 * skal == wert and any(k in lb.lower() for k in SCHLUESSEL[metric])), None)
                    if andere:
                        gefunden, status = andere, "gleich_andere_zeile"
                    else:
                        status = "abweichung" if gefunden else "nicht_gefunden"
                        # gleiche Ziffernfolge, aber andere Größenordnung der Seite: nur vermerken, nicht als bestätigt zählen
                        for n2, (skal, zl) in seiten.items():
                            for lb, w in zl:
                                if any(k in lb.lower() for k in SCHLUESSEL[metric]) and any(
                                        w2 != 0 and wert != 0 and (w2 * skal * 1000 == wert or w2 * skal == wert * 1000) for w2 in w):
                                    gefunden, status = (n2, lb, w[0] * skal), "skala_der_seite_abweichend"
                                    break
                            if status == "skala_der_seite_abweichend":
                                break
                n, label, orig = gefunden if gefunden else ("", "", "")
                ausgabe.append([uid, name, metric, tag, f"{beginn or ''}..{ende}", einheit, wert, orig, accn, f"R{n}" if n else "", label, status, date.today().isoformat()])
    with open(HIER / "pruefung_sec_fpi.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["unternehmen_id", "name", "kennzahl", "xbrl_tag", "periode", "einheit", "wert_datenbank", "wert_original", "accession", "seite", "zeilenbezeichnung", "status", "geprueft_am"])
        w.writerows(ausgabe)
    print(Counter(a[11] for a in ausgabe))


if __name__ == "__main__":
    main()
