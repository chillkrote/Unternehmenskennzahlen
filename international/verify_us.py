"""Gleicht die importierten SEC-Werte mit den Finanzberichtsseiten (R2.htm ... R9.htm) des Original-Filings ab.

Je Unternehmen und Kennzahl wird das jüngste Geschäftsjahr des jüngsten 10-K mit der entsprechenden Zeile im Filing verglichen.
Ergebnis: pruefung_us.csv (status gleich / abweichung / nicht_gefunden). Nur 'gleich' zählt als bestätigt; alles andere bleibt zu prüfen.
Aufruf: SEC_USER_AGENT=... INTERNATIONAL_DATABASE_URL=... python3 international/verify_us.py
"""
import csv
import html
import re
import sys
from datetime import date
from decimal import Decimal
from pathlib import Path

HIER = Path(__file__).resolve().parent
sys.path.insert(0, str(HIER))
import db  # noqa: E402
from httpsafe import SichererClient, atomar_speichern  # noqa: E402

LABELS = {   # metric -> mögliche Zeilenbezeichnungen (Regex, ganze Zeile), in Rangfolge
    "assets": [r"total assets"],
    "equity": [r"total (?:stockholders|shareholders|shareowners)[’'`]*s?[’'`]* equity", r"total (?:stockholders|shareholders|shareowners)[’'`]* equity", r"total .* equity attributable to .*", r"total equity"],
    "equity_incl_nci": [r"total equity", r"total (?:stockholders|shareholders|shareowners)[’'`]*s?[’'`]* equity"],
    "revenue": [r"total (?:net )?revenues?", r"net sales", r"total net sales", r"sales of goods and services|sales and other operating revenues", r"net operating revenues", r"revenues?", r"total sales and revenues", r"sales to customers"],
    "net_income": [r"net income(?: \(loss\))?(?: attributable to .*)?", r"net earnings(?: attributable to .*)?", r"net loss"],
    "net_income_incl_nci": [r"consolidated profit.*", r"profit of consolidated and affiliated companies", r"net income(?: \(loss\))?", r"net earnings", r"net loss"],
    "operating_cash_flow": [r"net cash (?:provided by|from|provided by \(used in\)|from \(used in\)|generated by) operating activities.*", r"net cash provided by operations", r"cash generated from operating activities"],
}
SEITEN = range(2, 13)
SCHLUESSEL = {   # Stichwörter, die eine Zeile für die Kennzahl plausibel machen, wenn nur der Wert (nicht die Standardbezeichnung) übereinstimmt
    "assets": ["assets"], "equity": ["equity"], "equity_incl_nci": ["equity"], "revenue": ["revenue", "sales"],
    "net_income": ["net income", "net earnings", "net loss", "profit"], "net_income_incl_nci": ["net income", "net earnings", "net loss", "profit"],
    "operating_cash_flow": ["operating activities", "operations"]}


def zahl(text):
    t = html.unescape(text).replace("$", "").replace(",", "").replace("\xa0", " ").strip()
    m = re.fullmatch(r"\(?\s*(-?[\d.]+)\s*\)?", t)
    if not m:
        return None
    v = Decimal(m.group(1))
    return -v if t.startswith("(") else v


def seite_lesen(text):
    """-> (skalierung, [(label, [werte]) ...])"""
    kopf = text[:6000]
    skal = Decimal(10) ** (9 if re.search(r"In Billions", kopf, re.I) else 6 if re.search(r"In Millions", kopf, re.I) else 3 if re.search(r"In Thousands", kopf, re.I) else 0)
    zeilen = []
    for row in re.split(r"</tr>", text):
        zellen = [re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", c))).strip() for c in re.findall(r"<t[dh][^>]*>(.*?)</t[dh]>", row, re.S)]
        werte = [w for w in (zahl(z) for z in zellen[1:]) if w is not None]   # leere Zellen und Fußnotenmarken überspringen
        if zellen and werte:
            zeilen.append((zellen[0], werte))
    return skal, zeilen


def main():
    client = SichererClient({"www.sec.gov"}, max_bytes=5_000_000)
    ausgabe = []
    with db.verbinden() as conn:
        entitaeten = conn.execute("SELECT e.id, e.legal_name, i.value FROM international.entity e JOIN international.identifier i ON i.entity_id=e.id AND i.scheme='CIK' ORDER BY e.id").fetchall()
        for uid, name, cik in entitaeten:
            accn, filed = conn.execute(
                "SELECT provenance->>'accn', max(reported_at) FROM international.fact WHERE entity_id=%s AND provenance->>'form'='10-K' "
                "GROUP BY 1 ORDER BY 2 DESC LIMIT 1", (uid,)).fetchone()
            seiten = {}
            for n in SEITEN:
                url = f"https://www.sec.gov/Archives/edgar/data/{int(cik)}/{accn.replace('-', '')}/R{n}.htm"
                pfad = HIER / "objektspeicher" / "sec" / "filings" / f"{accn}_R{n}.htm"
                if not pfad.exists():
                    try:
                        atomar_speichern(pfad.parent, pfad.name, client.holen(url))
                    except Exception as e:      # Seite nicht vorhanden: überspringen
                        continue
                seiten[n] = seite_lesen(pfad.read_text(encoding="utf-8", errors="ignore"))
            for metric in LABELS:
                zeile = conn.execute(
                    "SELECT value, period_end, period_start, provenance->>'tag' FROM international.fact WHERE entity_id=%s AND metric_code=%s AND provenance->>'accn'=%s "
                    "ORDER BY period_end DESC LIMIT 1", (uid, metric, accn)).fetchone()
                if not zeile:
                    continue
                wert, ende, beginn, tag = zeile
                gefunden = None
                for muster in LABELS[metric]:
                    for n, (skal, zl) in seiten.items():
                        for label, werte in zl:
                            if re.fullmatch(muster, label.strip().lower().rstrip(":")):
                                gefunden = (n, label, werte[0] * skal if werte[0] * skal == wert or werte[0] != wert else werte[0])
                                break
                        if gefunden:
                            break
                    if gefunden:
                        break
                if gefunden and gefunden[2] == wert:
                    status = "gleich"
                else:
                    andere = next(((n2, lb, w[0] * skal) for n2, (skal, zl) in seiten.items() for lb, w in zl
                                   if w[0] * skal == wert and any(k in lb.lower() for k in SCHLUESSEL[metric])), None)
                    if andere:
                        gefunden, status = andere, "gleich_andere_zeile"
                    else:
                        status = "abweichung" if gefunden else "nicht_gefunden"
                if gefunden:
                    n, label, orig = gefunden
                else:
                    n, label, orig = "", "", ""
                ausgabe.append([uid, name, metric, tag, f"{beginn or ''}..{ende}", wert, orig, accn, f"R{n}" if n else "", label, status, date.today().isoformat()])
    with open(HIER / "pruefung_us.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["unternehmen_id", "name", "kennzahl", "xbrl_tag", "periode", "wert_datenbank", "wert_original", "accession", "seite", "zeilenbezeichnung", "status", "geprueft_am"])
        w.writerows(ausgabe)
    from collections import Counter
    print(Counter(a[10] for a in ausgabe))


if __name__ == "__main__":
    main()
